import type { KavachTaskDef } from '../types/kavach';

/**
 * Dealer Kavach v2 — the checklist every outlet starts from (ADR 0057 §8).
 *
 * The same 45 points as the sheet `PUMP ASSESSMENT ORIGINAL.xlsx` (MAIN tab is
 * canonical): same codes, same serial numbers, same points. What is new is HOW
 * each one is proven — a photo the outlet sends, a sheet MDG makes for them to
 * fill and photograph, or data MDG already pulls — and the two lines that say
 * what to do and what the photo must show.
 *
 * Changes from the sheet, on purpose:
 *  - `insurance-renewal-reminder` was a daily point. A daily photo of an
 *    insurance paper is nonsense, so it is a yearly one.
 *  - Points with no clock in the sheet (SOS) are `everyDays: null`: "when it
 *    happens". They are sent from the Kavach tab and are not in the %.
 *
 * The boot seed writes these once; after that the database wins, so an admin's
 * edit is never undone by a deploy (`seed/kavachTasks.ts`).
 */
export type KavachTaskSeedRow = Omit<KavachTaskDef, 'active' | 'own' | 'overridden'>;

type Partial_ = Partial<KavachTaskSeedRow> &
  Pick<KavachTaskSeedRow, 'code' | 'srNo' | 'titleEn' | 'titleHi' | 'howToEn' | 'howToHi' | 'points' | 'group'>;

function p(row: Partial_): KavachTaskSeedRow {
  return {
    everyDays: 365,
    dueTime: null,
    how: 'photo',
    uploader: 'manager',
    source: null,
    sheet: null,
    panels: [],
    iocOnly: false,
    acceptsFile: false,
    sort: row.srNo * 10,
    ...row,
  };
}

